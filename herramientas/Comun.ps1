# Funciones compartidas por las herramientas de Spanish Lyrics.
# Compatible con Windows PowerShell 5.1 (el que viene con Windows).

$Utf8SinBom = New-Object System.Text.UTF8Encoding($false)
$Utf8ConBom = New-Object System.Text.UTF8Encoding($true)

$ColumnasCsv = @('tipo', 'pv_id', 'cancion', 'mod', 'linea', 'tiempo', 'japones', 'romaji', 'ingles', 'espanol')

function Get-CarpetaMods {
    param([string]$CarpetaJuego)
    $mods = Join-Path $CarpetaJuego 'mods'
    if (-not (Test-Path -LiteralPath $mods)) {
        throw "No se encontró la carpeta 'mods' en: $CarpetaJuego"
    }
    return $mods
}

# Lee un archivo de letras de LyricsPatch (lyrics = [ {time = ..., text = "..."}, ... ]).
# Devuelve una lista de objetos { Tiempo; Texto } en orden.
function Read-LyricsPatchToml {
    param([string]$Ruta)
    $lineas = [System.IO.File]::ReadAllLines($Ruta, $Utf8SinBom)
    $patron = '\{\s*time\s*=\s*([0-9:.]+)\s*,\s*text\s*=\s*"((?:[^"\\]|\\.)*)"'
    $resultado = New-Object System.Collections.Generic.List[object]
    foreach ($l in $lineas) {
        $m = [regex]::Match($l, $patron)
        if ($m.Success) {
            $resultado.Add([pscustomobject]@{
                Tiempo = $m.Groups[1].Value
                Texto  = ConvertFrom-TomlString $m.Groups[2].Value
            })
        }
    }
    return $resultado
}

# Nombre de la canción: LyricsPatch lo pone como comentario en la segunda línea ("# Alien Alien").
function Get-NombreDesdeToml {
    param([string]$Ruta)
    $lineas = [System.IO.File]::ReadAllLines($Ruta, $Utf8SinBom)
    foreach ($l in $lineas) {
        if ($l -match '^#\s*(.+)$' -and $l -notmatch 'autogenerated') { return $matches[1].Trim() }
        if ($l -match '^\s*lyrics\s*=') { break }
    }
    return ''
}

function ConvertFrom-TomlString {
    param([string]$Texto)
    # Solo se des-escapan las comillas. Las barras invertidas se dejan tal cual para que "\n"
    # (salto de línea en LyricsPatch) se vea y se pueda escribir igual en la planilla.
    return $Texto.Replace('\"', '"')
}

function ConvertTo-TomlString {
    param([string]$Texto)
    return $Texto.Replace('\"', '"').Replace('"', '\"')
}

# Lee un mod_pv_db.txt y devuelve un diccionario clave -> valor (mantiene el orden original de las claves).
function Read-PvDb {
    param([string]$Ruta)
    $dic = New-Object 'System.Collections.Specialized.OrderedDictionary'
    foreach ($l in [System.IO.File]::ReadAllLines($Ruta, $Utf8SinBom)) {
        if ($l.StartsWith('#') -or -not $l.Contains('=')) { continue }
        $i = $l.IndexOf('=')
        $dic[$l.Substring(0, $i)] = $l.Substring($i + 1)
    }
    return $dic
}

function Test-CsvTraduccion {
    param($Filas, [string]$Archivo)
    if (-not $Filas) { return $false }
    $nombres = $Filas[0].PSObject.Properties.Name
    foreach ($c in @('tipo', 'pv_id', 'linea', 'tiempo', 'espanol')) {
        if ($nombres -notcontains $c) {
            Write-Warning "$Archivo no tiene la columna '$c'. Se omite."
            return $false
        }
    }
    return $true
}

